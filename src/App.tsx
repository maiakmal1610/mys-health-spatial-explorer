import React, { useState, useEffect, useMemo } from "react";
import { Header } from "./components/Header";
import { Sidebar } from "./components/Sidebar";
import { MapView } from "./components/MapView";
import { DistrictDrawer } from "./components/DistrictDrawer";
import { HealthcareGeoJSON, DistrictProperties, MetricViewMode } from "./types";
import { Loader2 } from "lucide-react";

export function App() {
  const [geoData, setGeoData] = useState<HealthcareGeoJSON | null>(null);
  const [loading, setLoading] = useState(true);
  const [selectedDistrict, setSelectedDistrict] = useState<DistrictProperties | null>(null);
  const [selectedState, setSelectedState] = useState<string>("All States");
  const [searchQuery, setSearchQuery] = useState<string>("");
  const [metricMode, setMetricMode] = useState<MetricViewMode>("ratio");
  const [sortBy, setSortBy] = useState<string>("ratio_desc");

  // Load GeoJSON generated by pipeline
  useEffect(() => {
    const primaryUrl = `${import.meta.env.BASE_URL}data/districts_healthcare.geojson`;
    
    fetch(primaryUrl)
      .then((res) => {
        if (!res.ok) {
          return fetch("./data/districts_healthcare.geojson").then((r) => {
            if (!r.ok) throw new Error("Failed to load healthcare GeoJSON");
            return r.json();
          });
        }
        return res.json();
      })
      .then((data: HealthcareGeoJSON) => {
        setGeoData(data);
        setLoading(false);
      })
      .catch((err) => {
        console.error("Error loading geojson:", err);
        setLoading(false);
      });
  }, []);

  // Compute National Aggregates
  const districts = useMemo(() => {
    if (!geoData) return [];
    return geoData.features.map((f) => f.properties);
  }, [geoData]);

  const nationalTotals = useMemo(() => {
    if (!districts.length) return { totalBeds: 0, totalPop: 0, avgRatio: 0 };
    const beds = districts.reduce((acc, d) => acc + d.total_beds, 0);
    const pop = districts.reduce((acc, d) => acc + d.population, 0);
    const ratio = pop > 0 ? (beds / pop) * 1000 : 0;
    return {
      totalBeds: beds,
      totalPop: pop,
      avgRatio: ratio,
    };
  }, [districts]);

  if (loading) {
    return (
      <div className="h-screen w-screen bg-slate-950 flex flex-col items-center justify-center text-slate-300 gap-3">
        <Loader2 className="w-8 h-8 text-cyan-400 animate-spin" />
        <div className="text-sm font-medium">Loading Malaysia Healthcare Equity Spatial Exploration...</div>
        <div className="text-xs text-slate-500">Querying 159 administrative districts</div>
      </div>
    );
  }

  return (
    <div className="h-screen w-screen flex flex-col bg-slate-950 text-slate-100 overflow-hidden font-sans">
      <Header
        totalBeds={nationalTotals.totalBeds}
        totalPopulation={nationalTotals.totalPop}
        avgRatio={nationalTotals.avgRatio}
        districtsCount={districts.length}
      />

      <div className="flex-1 flex overflow-hidden relative">
        <Sidebar
          districts={districts}
          selectedDistrictId={selectedDistrict?.district_id || null}
          onSelectDistrict={(d) => setSelectedDistrict(d)}
          selectedState={selectedState}
          onSelectState={setSelectedState}
          searchQuery={searchQuery}
          onSearchChange={setSearchQuery}
          metricMode={metricMode}
          onMetricModeChange={setMetricMode}
          sortBy={sortBy}
          onSortByChange={setSortBy}
        />

        <main className="flex-1 relative h-full">
          <MapView
            geoData={geoData}
            selectedDistrictId={selectedDistrict?.district_id || null}
            selectedState={selectedState}
            onSelectDistrict={(d) => setSelectedDistrict(d)}
            metricMode={metricMode}
          />

          <DistrictDrawer
            district={selectedDistrict}
            onClose={() => setSelectedDistrict(null)}
          />
        </main>
      </div>
    </div>
  );
}

export default App;
